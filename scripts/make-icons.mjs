// Generates the app icons from the artwork below, in the FlosForge brand style
// (_flosforge_website/brand/svg: FlosForge, Reader, Guard, Toolbox): an edge-to-edge dark
// "metal" plate, one bold outline symbol in the FlosForge teal gradient, and one glowing accent.
// Rasterized with ImageMagick 7 + librsvg.
//
//   npm run icons
//
// macOS gets the same artwork on Apple's icon grid (an 824 px squircle with a 100 px margin and a
// soft shadow), like FlosForge Notes: recent macOS shrinks icons that aren't that shape onto a
// grey tile. Everywhere else the plate goes edge to edge, as in the brand files.
//
// macOS 26 and later draw old-style (.icns) icons shrunk onto a grey tile whatever their shape;
// only an Icon Composer icon escapes that. resources/icon.icon is one: the plate becomes its fill
// and the symbol its one layer, and macOS adds the shape, the glass and the shadow. Building with
// it needs Xcode 26 (its actool); scripts/dist.mjs uses it when that's installed.
//
// Writes:
//   resources/icon.svg          edge to edge (Windows, Linux, the in-app logo)
//   resources/icon-macos.svg    on Apple's grid
//   resources/icon.icns         macOS
//   resources/icon.ico          Windows (16–256 px)
//   resources/icon.png          Linux and the window icon
//   resources/icon-macos.png    the Dock icon during `npm start`
//   resources/icon.icon/        macOS 26+ (Icon Composer: icon.json and Assets/symbol.png)

import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const RES = fileURLToPath(new URL('../resources/', import.meta.url));

/** Superellipse ("squircle") path, close to Apple's continuous-corner app shape (as in Notes). */
function squircle(x, y, size, exponent = 5) {
  const r = size / 2;
  const points = [];
  for (let i = 0; i < 360; i++) {
    const t = (i / 360) * Math.PI * 2;
    const c = Math.cos(t);
    const s = Math.sin(t);
    points.push([x + r + r * Math.sign(c) * Math.abs(c) ** (2 / exponent), y + r + r * Math.sign(s) * Math.abs(s) ** (2 / exponent)]);
  }
  return 'M' + points.map(([px, py]) => `${px.toFixed(2)} ${py.toFixed(2)}`).join('L') + 'Z';
}

/**
 * On the brand's 200 px grid. A tablet, a line of handwriting, and the pen tip glowing where the
 * ink ends. `bold` thickens the strokes for the smallest sizes. `mac` puts it on Apple's grid.
 */
function iconSvg({ bold = false, mac = false, layer = false } = {}) {
  const outline = bold ? 12 : 8;
  const ink = bold ? 10 : 7;
  // Apple's grid: the 200 px design scaled onto an 824 px squircle at (100, 100) of 1024.
  const k = 824 / 200;
  const plate = layer
    ? ''
    : mac
    ? `<path d="${squircle(100, 100, 824)}" fill="url(#afMetalMac)" stroke="#24333F" stroke-width="${(2 * k).toFixed(1)}" filter="url(#afShadow)"/>`
    : `<rect width="200" height="200" rx="44" fill="url(#afMetal)" stroke="#24333F" stroke-width="2"/>`;
  const open = layer || mac
    ? '<svg width="1024" height="1024" viewBox="0 0 1024 1024" fill="none" xmlns="http://www.w3.org/2000/svg">'
    : '<svg width="200" height="200" viewBox="0 0 200 200" fill="none" xmlns="http://www.w3.org/2000/svg">';
  return `${open}
  <!-- Generated by scripts/make-icons.mjs; edit the artwork there. -->
  <defs>
    <linearGradient id="afMetalMac" x1="100" y1="100" x2="924" y2="924" gradientUnits="userSpaceOnUse">
      <stop offset="0%" stop-color="#14202B"/>
      <stop offset="100%" stop-color="#0A0E13"/>
    </linearGradient>
    <filter id="afShadow" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="10" stdDeviation="12" flood-color="#000000" flood-opacity="0.25"/>
    </filter>
    <linearGradient id="afMetal" x1="0" y1="0" x2="200" y2="200" gradientUnits="userSpaceOnUse">
      <stop offset="0%" stop-color="#14202B"/>
      <stop offset="100%" stop-color="#0A0E13"/>
    </linearGradient>
    <linearGradient id="afAccent" x1="52" y1="40" x2="148" y2="160" gradientUnits="userSpaceOnUse">
      <stop offset="0%" stop-color="#2DD4BF"/>
      <stop offset="100%" stop-color="#0891B2"/>
    </linearGradient>
    <filter id="afGlow" x="-60%" y="-60%" width="220%" height="220%">
      <feGaussianBlur stdDeviation="3" result="b"/>
      <feComposite in="SourceGraphic" in2="b" operator="over"/>
    </filter>
  </defs>

  <!-- App icon plate -->
  ${plate}
  ${layer ? `<g transform="scale(${1024 / 200})">` : mac ? `<g transform="translate(100 100) scale(${k})">` : '<g>'}

  <!-- Tablet -->
  <rect x="56" y="34" width="88" height="132" rx="14" stroke="url(#afAccent)" stroke-width="${outline}" stroke-linejoin="round"/>
  ${bold ? '' : `<path d="M76 62H124M76 78H108" stroke="url(#afAccent)" stroke-width="5" stroke-linecap="round" opacity="0.45"/>`}

  <!-- Handwriting -->
  <path d="M74 124C82 108 89 100 96 100C105 100 100 120 110 120C116 120 120 113 124 104"
    stroke="url(#afAccent)" stroke-width="${ink}" stroke-linecap="round" stroke-linejoin="round"/>

  <!-- Pen tip -->
  <circle cx="126" cy="100" r="${bold ? 8 : 6.5}" fill="url(#afAccent)" filter="url(#afGlow)"/>
  <circle cx="126" cy="100" r="${bold ? 3.5 : 2.6}" fill="#E9FFFB"/>
  </g>
</svg>
`;
}

const FULL = iconSvg();
const BOLD = iconSvg({ bold: true });
const MAC = iconSvg({ mac: true });
const MAC_BOLD = iconSvg({ mac: true, bold: true });
const LAYER = iconSvg({ layer: true });

/** Icon Composer's document: the plate's colour as the fill, the symbol as one glass layer. */
const ICON_JSON = {
  fill: { 'automatic-gradient': 'display-p3:0.08000,0.12500,0.16500,1.00000' },
  groups: [
    {
      layers: [{ 'image-name': 'symbol.png', name: 'symbol' }],
      shadow: { kind: 'neutral', opacity: 0.5 },
    },
  ],
  'supported-platforms': { circles: ['watchOS'], squares: 'shared' },
};

const tmp = mkdtempSync(join(tmpdir(), 'arem-icons-'));
const sources = {
  full: join(tmp, 'full.svg'),
  bold: join(tmp, 'bold.svg'),
  mac: join(tmp, 'mac.svg'),
  macBold: join(tmp, 'mac-bold.svg'),
  layer: join(tmp, 'layer.svg'),
};
writeFileSync(sources.full, FULL);
writeFileSync(sources.bold, BOLD);
writeFileSync(sources.mac, MAC);
writeFileSync(sources.macBold, MAC_BOLD);
writeFileSync(sources.layer, LAYER);

const cache = new Map();
/** The bold artwork below 48 px, so the strokes don't vanish. */
function png(size, mac = false) {
  const variant = mac ? (size < 48 ? 'macBold' : 'mac') : size < 48 ? 'bold' : 'full';
  const key = `${variant}:${size}`;
  if (!cache.has(key)) {
    const out = join(tmp, `${variant}-${size}.png`);
    execFileSync('magick', ['-background', 'none', '-density', mac ? '300' : '1200', sources[variant], '-resize', `${size}x${size}`, out]);
    cache.set(key, out);
  }
  return cache.get(key);
}

/** ICNS with PNG entries: a header and a list of (type, length, PNG). */
function icns(entries) {
  const chunks = entries.map(([type, file]) => {
    const data = readFileSync(file);
    const head = Buffer.alloc(8);
    head.write(type, 0, 'ascii');
    head.writeUInt32BE(data.length + 8, 4);
    return Buffer.concat([head, data]);
  });
  const body = Buffer.concat(chunks);
  const header = Buffer.alloc(8);
  header.write('icns', 0, 'ascii');
  header.writeUInt32BE(body.length + 8, 4);
  return Buffer.concat([header, body]);
}

try {
  writeFileSync(join(RES, 'icon.svg'), FULL);
  writeFileSync(join(RES, 'icon-macos.svg'), MAC);
  // Every size macOS asks for, including the @2x (Retina) variants of the small ones.
  writeFileSync(
    join(RES, 'icon.icns'),
    icns([
      ['icp4', png(16, true)],
      ['ic11', png(32, true)],
      ['icp5', png(32, true)],
      ['ic12', png(64, true)],
      ['ic07', png(128, true)],
      ['ic13', png(256, true)],
      ['ic08', png(256, true)],
      ['ic14', png(512, true)],
      ['ic09', png(512, true)],
      ['ic10', png(1024, true)],
    ])
  );
  writeFileSync(join(RES, 'icon-macos.png'), readFileSync(png(512, true)));
  execFileSync('magick', [...[16, 24, 32, 48, 64, 128, 256].map(png), join(RES, 'icon.ico')]);
  writeFileSync(join(RES, 'icon.png'), readFileSync(png(1024)));
  const composer = join(RES, 'icon.icon');
  rmSync(composer, { recursive: true, force: true });
  mkdirSync(join(composer, 'Assets'), { recursive: true });
  writeFileSync(join(composer, 'icon.json'), JSON.stringify(ICON_JSON, null, 2) + '\n');
  execFileSync('magick', ['-background', 'none', '-density', '300', sources.layer, '-resize', '1024x1024', '-depth', '8', join(composer, 'Assets', 'symbol.png')]);
  console.log('wrote icon.svg, icon-macos.svg, icon.icns, icon.ico, icon.png, icon-macos.png, icon.icon');
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
